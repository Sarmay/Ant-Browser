package launchcode

import (
	"bufio"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"strconv"
	"strings"
)

// CookieRecord 是 LaunchServer Cookie 接口使用的 Cookie 结构。
type CookieRecord struct {
	Name     string  `json:"name"`
	Value    string  `json:"value"`
	Domain   string  `json:"domain,omitempty"`
	Path     string  `json:"path,omitempty"`
	Expires  float64 `json:"expires,omitempty"`
	HTTPOnly bool    `json:"httpOnly,omitempty"`
	Secure   bool    `json:"secure,omitempty"`
	SameSite string  `json:"sameSite,omitempty"`
	URL      string  `json:"url,omitempty"`
}

type profileCookiesWriteRequest struct {
	Cookies  []CookieRecord `json:"cookies"`
	Netscape string         `json:"netscape"`
}

func (s *LaunchServer) handleProfileCookies(w http.ResponseWriter, r *http.Request, profileID string) {
	switch r.Method {
	case http.MethodGet:
		s.handleGetProfileCookies(w, r, profileID)
	case http.MethodPut, http.MethodPost:
		s.handleImportProfileCookies(w, r, profileID)
	default:
		writeJSON(w, http.StatusMethodNotAllowed, map[string]interface{}{
			"ok":    false,
			"error": "method not allowed",
		})
	}
}

func (s *LaunchServer) handleGetProfileCookies(w http.ResponseWriter, r *http.Request, profileID string) {
	manager, ok := s.starter.(BrowserCookieManager)
	if !ok {
		writeJSON(w, http.StatusServiceUnavailable, map[string]interface{}{
			"ok":    false,
			"error": "cookie api is not available",
		})
		return
	}

	cookies, err := manager.ListInstanceCookies(profileID)
	if err != nil {
		writeJSON(w, mapProfileWriteErrorStatus(err), map[string]interface{}{
			"ok":    false,
			"error": err.Error(),
		})
		return
	}

	netscape := formatNetscapeCookies(cookies)
	if strings.EqualFold(strings.TrimSpace(r.URL.Query().Get("format")), "netscape") {
		w.Header().Set("Content-Type", "text/plain; charset=utf-8")
		w.WriteHeader(http.StatusOK)
		_, _ = io.WriteString(w, netscape)
		return
	}

	writeJSON(w, http.StatusOK, map[string]interface{}{
		"ok":        true,
		"profileId": profileID,
		"count":     len(cookies),
		"cookies":   cookies,
		"netscape":  netscape,
	})
}

func (s *LaunchServer) handleImportProfileCookies(w http.ResponseWriter, r *http.Request, profileID string) {
	manager, ok := s.starter.(BrowserCookieManager)
	if !ok {
		writeJSON(w, http.StatusServiceUnavailable, map[string]interface{}{
			"ok":    false,
			"error": "cookie api is not available",
		})
		return
	}

	var req profileCookiesWriteRequest
	dec := json.NewDecoder(io.LimitReader(r.Body, 1<<20))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&req); err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]interface{}{
			"ok":    false,
			"error": "invalid request body",
		})
		return
	}

	cookies := req.Cookies
	if len(cookies) == 0 && strings.TrimSpace(req.Netscape) != "" {
		parsed, err := parseNetscapeCookies(req.Netscape)
		if err != nil {
			writeJSON(w, http.StatusBadRequest, map[string]interface{}{
				"ok":    false,
				"error": err.Error(),
			})
			return
		}
		cookies = parsed
	}
	if len(cookies) == 0 {
		writeJSON(w, http.StatusBadRequest, map[string]interface{}{
			"ok":    false,
			"error": "cookies is required",
		})
		return
	}

	imported, err := manager.ImportInstanceCookies(profileID, cookies)
	if err != nil {
		writeJSON(w, mapProfileWriteErrorStatus(err), map[string]interface{}{
			"ok":    false,
			"error": err.Error(),
		})
		return
	}

	writeJSON(w, http.StatusOK, map[string]interface{}{
		"ok":        true,
		"imported":  true,
		"profileId": profileID,
		"count":     imported,
	})
}

func formatNetscapeCookies(cookies []CookieRecord) string {
	var b strings.Builder
	b.WriteString("# Netscape HTTP Cookie File\n")
	b.WriteString("# Generated by Ant Browser\n\n")
	for _, cookie := range cookies {
		domain := strings.TrimSpace(cookie.Domain)
		if domain == "" {
			continue
		}
		includeSubdomains := "FALSE"
		if strings.HasPrefix(domain, ".") {
			includeSubdomains = "TRUE"
		}
		secure := "FALSE"
		if cookie.Secure {
			secure = "TRUE"
		}
		path := strings.TrimSpace(cookie.Path)
		if path == "" {
			path = "/"
		}
		expires := int64(cookie.Expires)
		if expires < 0 {
			expires = 0
		}
		fmt.Fprintf(&b, "%s\t%s\t%s\t%s\t%d\t%s\t%s\n",
			domain, includeSubdomains, path, secure, expires, cookie.Name, cookie.Value)
	}
	return b.String()
}

func parseNetscapeCookies(raw string) ([]CookieRecord, error) {
	scanner := bufio.NewScanner(strings.NewReader(raw))
	scanner.Buffer(make([]byte, 0, 64*1024), 1<<20)
	cookies := make([]CookieRecord, 0)
	lineNo := 0
	for scanner.Scan() {
		lineNo++
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.Split(line, "\t")
		if len(parts) < 7 {
			return nil, fmt.Errorf("invalid netscape cookie at line %d", lineNo)
		}
		expires, _ := strconv.ParseFloat(strings.TrimSpace(parts[4]), 64)
		path := strings.TrimSpace(parts[2])
		if path == "" {
			path = "/"
		}
		cookies = append(cookies, CookieRecord{
			Domain:  strings.TrimSpace(parts[0]),
			Path:    path,
			Secure:  strings.EqualFold(strings.TrimSpace(parts[3]), "TRUE"),
			Expires: expires,
			Name:    strings.TrimSpace(parts[5]),
			Value:   strings.Join(parts[6:], "\t"),
		})
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("invalid netscape cookie file")
	}
	if len(cookies) == 0 {
		return nil, fmt.Errorf("netscape cookie file has no cookies")
	}
	return cookies, nil
}
